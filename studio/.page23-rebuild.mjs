import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
const root = process.cwd();
const pageDir = join(root, 'library', '25d1aad102e4', 'pages', '023');
const runtime = join(process.env.USERPROFILE || '', '.cache', 'codex-runtimes', 'codex-primary-runtime', 'dependencies', 'node', 'node_modules');
const { createCanvas, loadImage } = await import(pathToFileURL(join(runtime, '@napi-rs', 'canvas', 'index.js')).href);
const layoutPath = join(pageDir, 'layout.json');
const layout = JSON.parse(await readFile(layoutPath, 'utf8'));
const box = (i, x, y, w, h = layout.blocks[i].box.h) => { layout.blocks[i].box = { x, y, w, h }; };
layout.blocks[0].box = { x: 0.091, y: 0.024, w: 0.14, h: 0.044 };
layout.blocks[0].k = 1.02;
box(1, 0, 0.088, 0.515, 0.045); layout.blocks[1].split = 0.60; layout.blocks[1].mascotBox = { x: 0.08, y: 0.078, w: 0.07, h: 0.054 };
box(2, 0.098, 0.153, 0.54); 
layout.blocks[3].stackTranslation = true;
box(4, 0.1227, 0.257, 0.34);
for (const [i, y] of [[5,0.284],[6,0.311],[7,0.338]]) box(i, 0.157, y, 0.58);
box(8, 0, 0.4145, 0.28, 0.043); layout.blocks[8].split = 0.72;
layout.blocks[9].stackTranslation = true;
box(10, 0.1227, 0.533, 0.43);
layout.blocks[11].k = 0.72;
layout.blocks[14].box = { x: 0.455, y: 0.572, w: 0.392, h: 0.199 };
layout.blocks[15].box = { x: 0.456, y: 0.792, w: 0.391, h: 0.113 };
layout.decorations = [];
layout.assets ||= {};
layout.assets['img-14'] = 'assets/img-14-photo.webp';
const scan = await loadImage(await readFile(join(pageDir, 'scan.png')));
const b = layout.blocks[14].box;
const sx = Math.round(b.x * scan.width), sy = Math.round(b.y * scan.height);
const sw = Math.round(b.w * scan.width), sh = Math.round(b.h * scan.height);
const c = createCanvas(sw, sh);
c.getContext('2d').drawImage(scan, sx, sy, sw, sh, 0, 0, sw, sh);
await writeFile(join(pageDir, 'assets', 'img-14-photo.webp'), await c.encode('webp', 94));
await writeFile(layoutPath, JSON.stringify(layout, null, 1));
const response = await fetch('http://127.0.0.1:4177/local/webbook/books/25d1aad102e4/pages/23/layout', {
  method: 'PUT', headers: { 'content-type': 'application/json' },
  body: JSON.stringify({ layout: { blocks: layout.blocks, decorations: layout.decorations, theme: layout.theme } })
});
const result = await response.json();
if (!response.ok) throw new Error(JSON.stringify(result));
console.log(JSON.stringify({ page: 23, crop: { sx, sy, sw, sh }, result }, null, 2));
